class PaymentConfirmationRequest(BaseModel):
    transaction_id: Optional[int] = None
    amount: float = Field(..., gt=0, description="Amount to deduct upon confirmation")


class PaymentConfirmationResponse(BaseModel):
    status: str = Field(..., description="SUCCESS or INSUFFICIENT_FUNDS")
    success: bool
    message: str
    transaction_id: Optional[int] = None
    amount: float
    previous_balance: float
    remaining_balance: float
    deducted: bool


class TopUpRequest(BaseModel):
    amount: float = Field(..., gt=0, le=10000000, description="Amount to add to demo balance in INR")

